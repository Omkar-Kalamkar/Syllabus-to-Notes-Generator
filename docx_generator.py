"""Create a formatted Word (.docx) file from generated Markdown notes."""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import datetime
from io import BytesIO
from typing import List, Optional

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor

from generator import SyllabusNotesError


BOLD_MARKDOWN_RE = re.compile(r"\*\*(.+?)\*\*")
HEADING_RE = re.compile(r"^(#{1,6})\s+(.+)$")
BULLET_RE = re.compile(r"^\s*[-*•\u2013]\s+(.+)$")
NUMBERED_RE = re.compile(r"^\s*\d+[.)]\s+(.+)$")


@dataclass
class NoteBlock:
    """A parsed line of generated notes."""

    kind: str
    text: str
    level: int = 0


class DocxGenerationError(SyllabusNotesError):
    """Raised when the Word document cannot be created."""


def _strip_inline_markdown(text: str) -> str:
    """Remove simple Markdown symbols that should not appear in Word output."""
    cleaned = text.replace("`", "")
    cleaned = cleaned.replace("**", "")
    return cleaned.strip()


def _add_inline_text(paragraph, text: str) -> None:
    """Add text to a paragraph while preserving **bold** Markdown."""
    position = 0
    for match in BOLD_MARKDOWN_RE.finditer(text):
        if match.start() > position:
            paragraph.add_run(text[position : match.start()])
        paragraph.add_run(match.group(1)).bold = True
        position = match.end()
    if position < len(text):
        paragraph.add_run(text[position:])


def parse_notes_to_blocks(notes_text: str) -> List[NoteBlock]:
    """Convert the Markdown-like Gemini output into simple document blocks."""
    blocks: List[NoteBlock] = []

    for raw_line in str(notes_text).replace("\r\n", "\n").split("\n"):
        line = raw_line.strip()
        if not line or set(line) <= {"-", "_", "*"}:
            continue

        heading = HEADING_RE.match(line)
        if heading:
            blocks.append(NoteBlock("heading", heading.group(2).strip(), len(heading.group(1))))
            continue

        bullet = BULLET_RE.match(line)
        if bullet:
            blocks.append(NoteBlock("bullet", bullet.group(1).strip()))
            continue

        numbered = NUMBERED_RE.match(line)
        if numbered:
            blocks.append(NoteBlock("number", numbered.group(1).strip()))
            continue

        blocks.append(NoteBlock("paragraph", line))

    return blocks


def _configure_styles(document: Document) -> None:
    """Apply a clean, consistent educational theme to the document."""
    normal = document.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(11)
    normal.paragraph_format.space_after = Pt(6)
    normal.paragraph_format.line_spacing = 1.15

    heading_colors = [
        RGBColor(31, 78, 121),
        RGBColor(46, 117, 182),
        RGBColor(68, 114, 196),
    ]
    heading_sizes = [16, 13, 11]

    for index, style_name in enumerate(("Heading 1", "Heading 2", "Heading 3")):
        style = document.styles[style_name]
        style.font.name = "Calibri"
        style.font.size = Pt(heading_sizes[index])
        style.font.bold = True
        style.font.color.rgb = heading_colors[index]
        style.paragraph_format.space_before = Pt(12)
        style.paragraph_format.space_after = Pt(6)


def _add_metadata(document: Document, subject_name: str, generated_on: str) -> None:
    """Add the project name, subject, and generation date below the title."""
    subtitle = document.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = subtitle.add_run("Generated by Syllabus-to-Notes Generator")
    run.italic = True
    run.font.size = Pt(10)
    run.font.color.rgb = RGBColor(100, 100, 100)

    metadata = document.add_paragraph()
    metadata.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if subject_name.strip():
        label = metadata.add_run("Subject: ")
        label.bold = True
        metadata.add_run(subject_name.strip())
        metadata.add_run("   |   ")
    date_label = metadata.add_run("Generated on: ")
    date_label.bold = True
    metadata.add_run(generated_on)

    document.add_paragraph("_" * 70)


def create_docx_bytes(
    notes_text: str,
    subject_name: str = "",
    generated_on: Optional[str] = None,
) -> bytes:
    """
    Build a .docx file in memory and return its bytes.

    Returning bytes lets Streamlit use the data directly in a download button without
    writing temporary files to disk.
    """
    if notes_text is None or not str(notes_text).strip():
        raise DocxGenerationError("There are no generated notes to export yet.")

    try:
        document = Document()
        _configure_styles(document)

        blocks = parse_notes_to_blocks(notes_text)
        title = "Study Notes"
        if blocks and blocks[0].kind == "heading" and blocks[0].level == 1:
            title = _strip_inline_markdown(blocks[0].text)
            blocks = blocks[1:]

        heading = document.add_heading(title, level=0)
        heading.alignment = WD_ALIGN_PARAGRAPH.CENTER

        date_text = generated_on or datetime.now().strftime("%d %B %Y")
        _add_metadata(document, subject_name, date_text)

        for block in blocks:
            if block.kind == "heading":
                # Gemini uses H2 for units and H3 for topics; Word uses Heading 1/2.
                word_level = {2: 1, 3: 2, 4: 3}.get(block.level, 1)
                document.add_heading(_strip_inline_markdown(block.text), level=word_level)
            elif block.kind == "bullet":
                paragraph = document.add_paragraph(style="List Bullet")
                _add_inline_text(paragraph, block.text)
            elif block.kind == "number":
                paragraph = document.add_paragraph(style="List Number")
                _add_inline_text(paragraph, block.text)
            else:
                paragraph = document.add_paragraph()
                _add_inline_text(paragraph, block.text)

        buffer = BytesIO()
        document.save(buffer)
        return buffer.getvalue()
    except DocxGenerationError:
        raise
    except Exception as exc:
        raise DocxGenerationError(
            f"Word document generation failed: {_safe_detail(exc)}"
        ) from exc


def _safe_detail(exc: Exception) -> str:
    """Keep technical DOCX errors short and free of sensitive values."""
    return str(exc)[:200]
